// Writes src/data/fixtures/products.gen.ts from the price bot's catalog (price-bot/catalog/items.csv),
// so the app's products and the bot's catalog stay one list. Run: npm run products:gen
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { loadCatalog, sizeLabel } from '../price-bot/catalog';

export function renderProductsModule() {
  const rows = loadCatalog().map((i) =>
    JSON.stringify([i.id, i.name, sizeLabel(i), i.category, i.refPrice, i.inDefaultBasket ? 1 : 0]),
  );
  return `// Generated by scripts/gen-products.ts from price-bot/catalog/items.csv. Do not edit by hand.
import type { ProductSeed } from '../products';

export const PRODUCT_SEEDS: ProductSeed[] = [
${rows.map((r) => `  ${r},`).join('\n')}
];
`;
}

if (require.main === module) {
  const out = join(__dirname, '..', 'src', 'data', 'fixtures', 'products.gen.ts');
  writeFileSync(out, renderProductsModule());
  console.log(`wrote ${out}`);
}
